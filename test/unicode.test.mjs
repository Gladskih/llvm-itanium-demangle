import assert from "node:assert/strict";
import { test } from "node:test";
import { createDemangler } from "../dist/node.js";
const api = await createDemangler();
// Itanium ABI 5.1.2: source-name length counts UTF-8 bytes.
test("preserves UTF-8 identifiers and byte consumption", () => {
  const result = api.demangleWithText("_Z2πv");
  assert.equal(result.status, "success");
  assert.equal(result.text, "π()");
  assert.equal(result.consumed, 6);
  assert.equal(result.ast.nodes[1].name, "π");
  assert.equal(api.demangleTypeWithText("4😊").text, "😊");
});
// libcxxabi/test/DemangleTestCases.inc: UTF-8 in char array initializer lists.
test("preserves UTF-8 generated by LLVM's native literal printer", () => {
  assert.equal(api.demangleWithText("_Z1fIXtl5HellotlA6_cLc240ELc159ELc152ELc138ELc33EEEEEvv").text,
    'void f<Hello{"😊!"}>()');
});
test("rejects lone surrogates and incorrect byte lengths", () => {
  assert.equal(api.demangleType("1π").status, "invalid");
  assert.equal(api.demangle("_Z1\ud800v").status, "invalid");
});
